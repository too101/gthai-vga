"""Generate the full-row specialization from the shared layout parser.
Run after parser edits; --check verifies the checked-in assembly is current.
The assembler itself has no Python dependency.
"""
from pathlib import Path
import re,sys
root=Path(__file__).resolve().parents[1]
p=root/'GTHAI.ASM';s=p.read_text(encoding='latin1')
body=s[s.index('RENDER_ROW_BODY PROC NEAR'):s.index('RENDER_ROW_BODY ENDP')+len('RENDER_ROW_BODY ENDP')]
body,n=re.subn(r'         CMP BYTE PTR CS:\[ROW_DESC_ACTIVE\],0\n         JE (\w+)\n         CALL RECORD_DESC_FONT[12]\n\1:\n','',body)
assert n==2,n
body,n=re.subn(r'         CMP BYTE PTR CS:\[ROW_DESC_ACTIVE\],0\n         JE (\w+)\n         MOV CS:\[CURRENT_RENDER_DESC\+\d+\],AL\n\1:\n','',body)
assert n==3,n
body,n=re.subn(r'         CMP BYTE PTR CS:\[ROW_DESC_ACTIVE\],0\n         JE (\w+)\n         XOR CX,CX\n         JMP SHORT (\w+)\n\1:\n         CALL (COPY_GLYPH19|OR_GLYPH_ROWS)\n\2:\n',lambda m:'         CALL '+m[3]+'\n',body)
assert n==4,n
labels=re.findall(r'^(\w+):',body,re.M)
for label in sorted(labels,key=len,reverse=True):body=re.sub(r'\b'+re.escape(label)+r'\b','FULL_'+label,body)
body=body.replace('RENDER_ROW_BODY','RENDER_FULL_ROW').replace('CALL CLASSIFY_ROW_CELL','CALL CLASSIFY_FULL_ROW_CELL').replace('CALL BLANK_TEXT_RUN','CALL BLANK_TEXT_RUN_FULL').replace('CALL WORD PTR CS:[ROW_BLANK_WRITER]','CALL L6289H')
body='\n'.join(line.rstrip() for line in body.split('\n'))
start='; BEGIN GENERATED FULL ROW RENDERER'
end='; END GENERATED FULL ROW RENDERER'
block=start+'\n; Generated by tools/generate_full_renderer.py; edit RENDER_ROW_BODY instead.\n'+body+'\n'+end
if start in s:
 result=s[:s.index(start)]+block+s[s.index(end)+len(end):]
else:
 at=s.index('RENDER_ROW_BODY ENDP')+len('RENDER_ROW_BODY ENDP')
 result=s[:at]+'\n\n'+block+s[at:]
if '--check' in sys.argv:
 assert result==s,'Full-row specialization is stale: run tools/generate_full_renderer.py'
 print('PASS: full-row specialization matches the shared layout parser')
else:p.write_text(result,encoding='latin1',newline='\r\n')
